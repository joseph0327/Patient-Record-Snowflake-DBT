{{ dbt_utils.generate_surrogate_key(
    [
        'INSURANCE_ID',
        'DBT_VALID_FROM'
    ]
) }} AS INSURANCE_SK,

INSURANCE_ID,

PATIENT_ID,

INSURANCE_NUMBER,

INSURANCE_COMPANY,

PLAN_NAME,

COVERAGE_AMOUNT,

EFFECTIVE_DATE,

EXPIRATION_DATE,

STATUS,

